import { randomUUID } from "crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "fs";
import { join } from "path";
import { FELLO_DIR } from "../backend/storage/constant";
import type { AssistantConfig } from "../shared/schema";
import { assistantWorkspaceName } from "../shared/assistant";

export const ASSISTANTS_DIR = join(FELLO_DIR, "assistants");
export const ASSISTANT_WORKSPACES_DIR = join(FELLO_DIR, "workspaces");

export const DEFAULT_ASSISTANT_DREAM = {
  maxContextTokens: 96_000,
  preferredTime: "02:00",
} as const;

export interface AssistantPaths {
  root: string;
  configPath: string;
  /** The assistant's single model session: runtime state and model history. */
  sessionDir: string;
  /** UI chat transcript segments. */
  chatDir: string;
  /** Long-term memory content produced by Dream. */
  memoryDir: string;
  diaryDir: string;
  remindersDir: string;
  remindersPath: string;
  /** Delegated ACP sub-agent records and transcripts. */
  workersDir: string;
  workspace: string;
}

export function assistantRoot(assistantId: string): string {
  return join(ASSISTANTS_DIR, assistantId);
}

export function assistantWorkspacePath(assistantId: string): string {
  return join(ASSISTANT_WORKSPACES_DIR, assistantWorkspaceName(assistantId));
}

export function assistantPaths(assistantId: string): AssistantPaths {
  const root = assistantRoot(assistantId);
  const memoryDir = join(root, "memory");
  const remindersDir = join(root, "reminders");
  return {
    root,
    configPath: join(root, "config.json"),
    sessionDir: join(root, "session"),
    chatDir: join(root, "chat"),
    memoryDir,
    diaryDir: join(memoryDir, "diary"),
    remindersDir,
    remindersPath: join(remindersDir, "reminders.json"),
    workersDir: join(root, "workers"),
    workspace: assistantWorkspacePath(assistantId),
  };
}

export function ensureAssistantDirectories(assistantId: string): AssistantPaths {
  const paths = assistantPaths(assistantId);
  mkdirSync(paths.sessionDir, { recursive: true });
  mkdirSync(paths.chatDir, { recursive: true });
  mkdirSync(paths.memoryDir, { recursive: true });
  mkdirSync(paths.diaryDir, { recursive: true });
  mkdirSync(paths.remindersDir, { recursive: true });
  mkdirSync(paths.workersDir, { recursive: true });
  mkdirSync(paths.workspace, { recursive: true });
  return paths;
}

function normalizeName(value: unknown): string {
  // Configs are always created with a name; this is only a last-resort fallback for
  // hand-edited files. Localized auto-names are generated by the manager on create.
  return typeof value === "string" && value.trim() ? value.trim() : "Personal Assistant";
}

function normalizeStringArray(value: unknown): string[] {
  return Array.isArray(value)
    ? [...new Set(value.filter((item): item is string => typeof item === "string" && !!item))]
    : [];
}

function normalizeConfig(id: string, raw: Record<string, unknown>): AssistantConfig {
  const dreamRaw =
    raw.dream && typeof raw.dream === "object" && !Array.isArray(raw.dream)
      ? (raw.dream as Record<string, unknown>)
      : null;
  const maxContextTokens = dreamRaw?.maxContextTokens;
  const preferredTime = dreamRaw?.preferredTime;
  const createdAt = typeof raw.createdAt === "number" ? raw.createdAt : Date.now();
  return {
    id,
    name: normalizeName(raw.name),
    disabled: raw.disabled === true,
    createdAt,
    sourceAgentId:
      typeof raw.sourceAgentId === "string" && raw.sourceAgentId.trim()
        ? raw.sourceAgentId.trim()
        : null,
    mcpServers: normalizeStringArray(raw.mcpServers),
    dream: {
      maxContextTokens:
        typeof maxContextTokens === "number" &&
        Number.isSafeInteger(maxContextTokens) &&
        maxContextTokens > 0
          ? maxContextTokens
          : DEFAULT_ASSISTANT_DREAM.maxContextTokens,
      preferredTime:
        typeof preferredTime === "string" && /^([01]\d|2[0-3]):[0-5]\d$/.test(preferredTime)
          ? preferredTime
          : DEFAULT_ASSISTANT_DREAM.preferredTime,
    },
  };
}

export function loadAssistantConfig(assistantId: string): AssistantConfig | null {
  if (
    !assistantId ||
    assistantId === "." ||
    assistantId === ".." ||
    assistantId.includes("/") ||
    assistantId.includes("\\")
  ) {
    return null;
  }
  const path = assistantPaths(assistantId).configPath;
  if (!existsSync(path)) return null;
  try {
    const raw: unknown = JSON.parse(readFileSync(path, "utf8"));
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) return null;
    return normalizeConfig(assistantId, raw as Record<string, unknown>);
  } catch (error) {
    console.error(`[assistant] Failed to read ${path}:`, error);
    return null;
  }
}

/** All assistant configs, oldest first (sidebar order). */
export function listAssistantConfigs(): AssistantConfig[] {
  if (!existsSync(ASSISTANTS_DIR)) return [];
  const configs: AssistantConfig[] = [];
  for (const entry of readdirSync(ASSISTANTS_DIR)) {
    if (entry.startsWith(".")) continue;
    const config = loadAssistantConfig(entry);
    if (config) configs.push(config);
  }
  return configs.sort((a, b) => a.createdAt - b.createdAt || a.id.localeCompare(b.id));
}

function writeConfigAtomic(config: AssistantConfig): void {
  const paths = assistantPaths(config.id);
  mkdirSync(paths.root, { recursive: true });
  const temporaryPath = `${paths.configPath}.tmp`;
  writeFileSync(temporaryPath, `${JSON.stringify(config, null, 2)}\n`, "utf8");
  renameSync(temporaryPath, paths.configPath);
}

export function saveAssistantConfig(config: AssistantConfig): AssistantConfig {
  const normalized = normalizeConfig(config.id, config as unknown as Record<string, unknown>);
  writeConfigAtomic(normalized);
  return normalized;
}

export function createAssistantConfig(input: {
  name: string;
  sourceAgentId: string;
  mcpServers: string[];
}): AssistantConfig {
  let id: string;
  do {
    id = `pa_${randomUUID().replace(/-/g, "").slice(0, 8)}`;
  } while (existsSync(assistantRoot(id)));

  const config: AssistantConfig = {
    id,
    name: input.name.trim() || "Personal Assistant",
    disabled: false,
    createdAt: Date.now(),
    sourceAgentId: input.sourceAgentId.trim() || null,
    mcpServers: normalizeStringArray(input.mcpServers),
    dream: { ...DEFAULT_ASSISTANT_DREAM },
  };
  ensureAssistantDirectories(id);
  return saveAssistantConfig(config);
}

export function updateAssistantConfig(
  assistantId: string,
  patch: Partial<
    Pick<AssistantConfig, "name" | "disabled" | "sourceAgentId" | "mcpServers" | "dream">
  >,
): AssistantConfig {
  const current = loadAssistantConfig(assistantId);
  if (!current) throw new Error(`Assistant ${assistantId} does not exist.`);
  const next = normalizeConfig(assistantId, {
    ...current,
    ...(patch.name !== undefined ? { name: patch.name } : {}),
    ...(patch.disabled !== undefined ? { disabled: patch.disabled } : {}),
    ...(patch.sourceAgentId !== undefined ? { sourceAgentId: patch.sourceAgentId } : {}),
    ...(patch.mcpServers !== undefined ? { mcpServers: patch.mcpServers } : {}),
    ...(patch.dream !== undefined ? { dream: patch.dream } : {}),
  });
  return saveAssistantConfig(next);
}

/** Hard delete: removes both the assistant data directory and its workspace. */
export function deleteAssistantData(assistantId: string): void {
  const paths = assistantPaths(assistantId);
  rmSync(paths.root, { recursive: true, force: true });
  rmSync(paths.workspace, { recursive: true, force: true });
}
